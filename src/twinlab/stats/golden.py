#: `docs/07` §10's agreement bound. Every pinned statistic must match to better than this.
TOLERANCE = 0.001

#: Respondents in the reference dataset. Large enough for a 46-column model to be identified,
#: small enough that the whole battery runs inside a CI step.
GOLDEN_N = 120

#: The seed of this module's own PRNG. Changing it changes the dataset and every expected value.
GOLDEN_SEED = 20260929

#: Bootstrap samples used by the golden run. **Deliberately the hard floor** (`docs/07` §9): it
#: keeps CI fast and it exercises the floor itself. It is far below reportable, which is exactly
#: why no number from this run is ever presented as a finding.
GOLDEN_BOOTSTRAP = 30

#: `docs/01` §5's four arms, cycled so every arm has equal representation.
GOLDEN_ARMS = ("BASE", "MGT1", "CON1", "REP1")


class _Prng:
    """A deterministic PRNG that belongs to this repository and cannot be upgraded underneath it.

    A 64-bit linear congruential generator (Knuth's MMIX constants) feeding a Box–Muller-free
    approximate normal built from twelve uniforms. Not a good PRNG for simulation — it does not
    need to be. It needs to produce the *same* numbers in 2026 and in 2030, on every platform.
    """

    __slots__ = ("_state",)

    _A = 6364136223846793005
    _C = 1442695040888963407
    _M = 1 << 64

    def __init__(self, seed: int) -> None:
        self._state = seed % self._M

    def uniform(self) -> float:
        self._state = (self._A * self._state + self._C) % self._M
        # The top 53 bits: the low bits of an LCG are famously weak.
        return (self._state >> 11) / float(1 << 53)

    def normal(self) -> float:
        """Irwin–Hall: the sum of twelve uniforms, minus six, has mean 0 and variance 1."""
        return sum(self.uniform() for _ in range(12)) - 6.0


def golden_rows(
    ref: ReferenceData | None = None, spec: ModelSpec | None = None
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """The fixture's submissions and answers, exactly as intake would have stored them.

    Every answer is an integer on its **own** item's published scale, and a reverse-worded item is
    answered the way a real respondent answers it — low when the construct is high. That is what
    makes "not reversed before estimation" a detectable fault rather than a cosmetic one.

    The latent structure matches the model in `twinlab.stats.spec` so the estimate is identified:
    an arm effect on the two perception constructs, those on the two justice constructs, those on
    satisfaction, and satisfaction plus dependence on the three intentions.
    """
    ref = ref or reference()
    spec = spec or build_model_spec(ref)
    rng = _Prng(GOLDEN_SEED)

    submissions: list[dict[str, Any]] = []
    answers: list[dict[str, Any]] = []

    for index in range(GOLDEN_N):
        submission_id = f"GOLD{index:04d}"
        arm = GOLDEN_ARMS[index % len(GOLDEN_ARMS)]
        submissions.append(
            {
                "submission_id": submission_id,
                "data_type": "REAL",
                "consented": True,
                "attention_passed": True,
                "completion_seconds": 1200,
                "speeder": False,
                "straight_liner": False,
                "arm": arm,
            }
        )

        treated = 0.0 if arm == "BASE" else 1.0
        expo = 0.55 * treated + rng.normal()
        ctrl = 0.40 * treated + rng.normal()
        fair = 0.45 * expo + 0.30 * ctrl + rng.normal()
        tran = 0.35 * expo + 0.35 * ctrl + rng.normal()
        sati = 0.50 * fair + 0.40 * tran + rng.normal()
        edep = rng.normal()
        latent = {
            "EXPO": expo, "CTRL": ctrl, "FAIR": fair, "TRAN": tran, "SATI": sati,
            "EDEP": edep,
            "LOYA": 0.55 * sati + 0.20 * edep + rng.normal(),
            "VOIC": -0.45 * sati + 0.25 * edep + rng.normal(),
            "EXIT": -0.50 * sati + 0.30 * edep + rng.normal(),
        }

        for construct in spec.constructs:
            if not construct.reflective:
                continue
            score = latent[construct.code]
            for item_id in construct.items:
                answers.append(
                    {
                        "submission_id": submission_id,
                        "item_id": item_id,
                        "value_num": _as_response(score, item_id, ref, rng),
                        "legacy_scale": False,
                    }
                )

    return submissions, answers


def _as_response(
    score: float, item_id: str, ref: ReferenceData, rng: _Prng
) -> int:
    """One latent score as an integer on the item's own published scale.

    The reverse step is the point of the fixture: an item the register flags ``reverse_coded`` is
    **stored inverted**, because that is how a respondent answers a negatively worded stem. The
    dataset builder reverses it back, and a build that does not will see that item correlate
    negatively with the rest of its block.
    """
    points = ref.scale_points(item_id)
    midpoint = (points + 1) / 2
    # 0.8 loading on the construct, the rest item-specific noise.
    observed = 0.8 * score + 0.6 * rng.normal()
    value = int(round(midpoint + observed * (points - 1) / 5.0))
    value = max(1, min(points, value))
    if ref.items[item_id].reverse_coded:
        value = (points + 1) - value
    return value


def unreversed_answers(
    ref: ReferenceData | None = None, spec: ModelSpec | None = None
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """The fixture with reverse-worded items left in the direction they were asked.

    **The second fault `docs/07` §10 requires the golden test to catch.** Note there is no
    production flag that does this: reverse coding is unconditional in
    :func:`twinlab.stats.dataset.build_matrix`, so the fault has to be injected into the *data*.
    A parameter that switched it off would be a parameter someone could set.
    """
    ref = ref or reference()
    submissions, answers = golden_rows(ref, spec)
    undone = []
    for row in answers:
        item_id = str(row["item_id"])
        if ref.items[item_id].reverse_coded:
            points = ref.scale_points(item_id)
            row = {**row, "value_num": (points + 1) - int(row["value_num"])}
        undone.append(row)
    return submissions, undone


def miswired_spec(ref: ReferenceData | None = None) -> ModelSpec:
    """The model with two items swapped between constructs.

    **The first fault `docs/07` §10 requires the golden test to catch.** `SAT1` is moved onto
    `TRAN` and `CLAR1` onto `SATI`. Both constructs keep their item count, both still estimate,
    every statistic still looks like a statistic — and the fingerprint moves, which is the point.
    """
    spec = build_model_spec(ref)
    swapped = []
    for construct in spec.constructs:
        items = list(construct.items)
        if construct.code == "SATI":
            items = ["CLAR1" if i == "SAT1" else i for i in items]
        elif construct.code == "TRAN":
            items = ["SAT1" if i == "CLAR1" else i for i in items]
        swapped.append(construct.model_copy(update={"items": tuple(items)}))
    return spec.model_copy(update={"constructs": tuple(swapped)})


def golden_matrix(
    ref: ReferenceData | None = None, spec: ModelSpec | None = None
) -> CaseMatrix:
    """The screened reference matrix. Screening drops nobody: the fixture is clean by design."""
    ref = ref or reference()
    spec = spec or build_model_spec(ref)
    submissions, answers = golden_rows(ref, spec)
    return build_matrix(
        submissions, answers,
        population="real", screening="strict", spec=spec, ref=ref,
    )


def matrix_digest(matrix: CaseMatrix) -> str:
    """A stable digest of the matrix's own numbers.

    Pinned by the golden test **before** any statistic is compared, so a changed fixture reports
    itself as a changed fixture rather than as forty drifting statistics.
    """
    payload = ";".join(matrix.columns) + "|" + "|".join(
        ",".join(f"{v:.6f}" for v in row) for row in matrix.rows
    )
    return hashlib.sha256(payload.encode()).hexdigest()[:32]


