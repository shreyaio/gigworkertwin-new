async def survey_counts(backend: DbBackend | None = None) -> GeneratorCounts:
    """`docs/06` §4's status line, from Supabase. Never a cached or assumed figure."""
    counts = await counts_by_type(backend or get_backend())
    real = counts.get(REAL_DATA_TYPE, 0)
    synthetic = counts.get(SYNTHETIC_DATA_TYPE, 0)
    return GeneratorCounts(
        real=real,
        synthetic=synthetic,
        line=(
            f"In the database now: {real:,} real "
            f"{'survey' if real == 1 else 'surveys'} and {synthetic:,} synthetic "
            f"{'survey' if synthetic == 1 else 'surveys'}."
        ),
    )


def preview(spec: GeneratorSpec, *, n: int = PREVIEW_N) -> list[GeneratorPreview]:
    """Derive the first ``n`` respondents of the batch ``spec`` describes. **Inserts nothing.**

    `docs/06` §4 is explicit that preview "derives a preview only, inserts nothing", so this
    builds the rows in memory and returns view models. It takes no backend, which is the
    strongest form of that guarantee: a function with no database handle cannot write one.

    The rows are the batch's real first ``n`` respondents, not a separate sample — the same
    seed and the same draw order — so what the preview shows is what *Generate surveys* would
    store.
    """
    peek = min(n, spec.count)
    batch = generate_batch(seed=spec.seed, count=peek, name=spec.name, spec=spec)
    out: list[GeneratorPreview] = []
    for submission, payload in zip(batch["submissions"], batch["payloads"], strict=True):
        answers = [
            row for row in batch["answers"]
            if row["submission_id"] == submission["submission_id"]
            and row.get("value_num") is not None
        ]
        mean = sum(float(r["value_num"]) for r in answers) / len(answers) if answers else None
        out.append(
            GeneratorPreview(
                response_id=str(submission["submission_id"]),
                city=str(submission.get("city") or ""),
                service=str(submission.get("service") or ""),
                arm=str(submission.get("arm") or ""),
                age=_answer(payload, "field:age"),
                gender=_answer(payload, "field:gender"),
                hours_per_week=_answer(payload, "field:hours_per_week"),
                # The payload answers the Form's years question; the dashboard and the twin row
                # both speak in months, so the preview shows what was set.
                tenure_months=_months_from_years(_answer(payload, "field:tenure_years")),
                # Formatted here, never in a Gradio handler (`docs/05` §8.4 rule 5).
                mean_answer="—" if mean is None else f"{mean:.2f}",
                items_answered=len(answers),
            )
        )
    return out


def _answer(payload: dict[str, Any], target: str) -> str:
    """One answer out of a Form-shaped payload, by its `form_map.yaml` target.

    Looked up through the map rather than by matching the question's wording: the Form's titles
    carry an en dash and a full sentence, and a preview column that silently blanked whenever
    someone reworded a question would be worse than no column. An unmapped target raises,
    because `form_map.yaml` is the contract both the real and the synthetic path answer.
    """
    titles = {value: key for key, value in form_map().items()}
    key = titles.get(target)
    if key is None:
        raise KeyError(f"form_map.yaml has no question for {target!r}")
    section, _, title = key.partition("|")
    for answer in payload["answers"]:
        if answer["section"] == section and answer["title"] == title:
            value = answer["value"]
            return ", ".join(map(str, value)) if isinstance(value, list) else str(value)
    return ""


def _months_from_years(years: str) -> str:
    """The Form's years answer read back as months. The inverse of ``years_from_months``.

    Rounded, never truncated, so the value the dashboard set is the value the preview shows: the
    two are the same number and a preview that disagreed with its own controls would be worse
    than no preview. An unparseable answer is shown as it stands rather than guessed at.
    """
    try:
        return str(round(float(years) * 12))
    except (TypeError, ValueError):
        return years


async def generate_and_store(
    spec: GeneratorSpec,
    *,
    backend: DbBackend | None = None,
    storage: StorageBackend | None = None,
) -> dict[str, Any]:
    """`docs/06` §4's *Generate surveys*. **Raw objects first, then rows** (I16).

    The batch is derived from ``spec`` alone and is reproducible from ``(seed, count, spec)``
    (`docs/09` §2). Ordering is :func:`services.surveys.store_batch`'s, which is the same
    ordering live intake uses: a synthetic row whose raw object is missing is a different kind of
    record from a real one, and `replay_raw.py` would report it as an orphan forever.

    This function is the whole of the button. The page passes the dashboard and renders what
    comes back; nothing about storing a batch lives in a Gradio handler (`docs/05` §8.4 rule 1).
    """
    from twinlab.services.surveys import store_batch

    batch = generate_batch(
        seed=spec.seed, count=spec.count, name=spec.name, spec=spec
    )
    result = await store_batch(
        batch, storage=storage or get_storage(), backend=backend or get_backend()
    )
    return {
        **result,
        "answers": len(batch["answers"]),
        "raw_objects": len(batch["payloads"]),
    }


def default_spec(seed: int, **overrides: Any) -> GeneratorSpec:
    """The dashboard's opening state, from `config/generator.default.yaml`."""
    return spec_from_config(seed, **overrides)


async def delete_all_synthetic(
    backend: DbBackend | None = None, *, skip_blocked: bool = False
) -> dict[str, Any]:
    """`docs/06` §4's *Delete all synthetic surveys*. Confirmed in the UI, counted here.

    A thin pass-through to :func:`services.surveys.delete_synthetic`, which is where the safety
    properties live — keyed on `data_type` alone, twins matched by source *and* id, no run touched,
    and the pre-flight that refuses with a sentence rather than a foreign-key traceback
    (`ARCHITECTURE_UPDATE.md` §3.4). It is re-exported rather than reimplemented so there is
    exactly one delete.
    """
    return await delete_synthetic(backend or get_backend(), skip_blocked=skip_blocked)


async def delete_preflight(backend: DbBackend | None = None) -> dict[str, Any]:
    """What *Delete all synthetic surveys* would do, before it does it. §3.4 step 1.

    Re-exported for the same reason as the delete: the screen must not reach past the service
    layer, and the counting has one home.
    """
    return await synthetic_delete_preflight(backend or get_backend())


